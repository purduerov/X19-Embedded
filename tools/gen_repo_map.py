#!/usr/bin/env python3
"""Generate a compact, deterministic symbol map of X19-Embedded public headers."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

TOOLS_DIR = Path(__file__).resolve().parent
if str(TOOLS_DIR) not in sys.path:
    sys.path.insert(0, str(TOOLS_DIR))

import check_layers  # noqa: E402

REPO_ROOT = TOOLS_DIR.parent
DEFAULT_OUT = REPO_ROOT / "docs" / "REPO_MAP.md"

HEADER_GLOBS = (
    "shared/include/**/*.h",
    "drivers/include/**/*.h",
    "services/include/**/*.h",
)

TYPEDEF_END_RE = re.compile(r"^\s*\}\s*([A-Za-z_][A-Za-z0-9_]*_t)\s*;")
TYPEDEF_ALIAS_RE = re.compile(r"^\s*typedef\s+.+?\s+([A-Za-z_][A-Za-z0-9_]*_t)\s*;")
FN_PROTO_RE = re.compile(
    r"^\s*(?:static\s+inline\s+|extern\s+)?([A-Za-z_][A-Za-z0-9_\s\*]+?\s+[A-Za-z_][A-Za-z0-9_]*\s*\([^;{}]*\))\s*;"
)


def _extract_symbols(header: Path) -> tuple[list[str], list[str]]:
    raw = header.read_text(encoding="utf-8", errors="replace")
    stripped = check_layers.strip_comments(raw)
    types: list[str] = []
    protos: list[str] = []

    for line in stripped.splitlines():
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        m_end = TYPEDEF_END_RE.match(s)
        if m_end:
            tname = m_end.group(1)
            if tname not in types:
                types.append(tname)
            continue
        m_alias = TYPEDEF_ALIAS_RE.match(s)
        if m_alias:
            tname = m_alias.group(1)
            if tname not in types:
                types.append(tname)
            continue
        m_fn = FN_PROTO_RE.match(s)
        if m_fn and not s.startswith(("typedef ", "return ")):
            sig = " ".join(m_fn.group(1).split())
            if len(sig) <= 110:
                protos.append(sig)

    return types, protos


def build_repo_map(root: Path = REPO_ROOT) -> str:
    headers: list[Path] = []
    for pat in HEADER_GLOBS:
        headers.extend(p for p in root.glob(pat) if p.is_file())
    headers = sorted(set(headers))

    lines = [
        "# X19-Embedded Public Header Symbol Map",
        "",
        "Auto-generated by `python rov.py map`. Read this before opening multiple headers.",
        "",
    ]

    for h in headers:
        rel = h.relative_to(root).as_posix()
        types, protos = _extract_symbols(h)
        if not types and not protos:
            continue
        lines.append(f"## `{rel}`")
        if types:
            lines.append(f"- Types: {', '.join(f'`{t}`' for t in types)}")
        for sig in protos[:15]:
            lines.append(f"- `{sig};`")
        if len(protos) > 15:
            lines.append(f"- ... (+{len(protos) - 15} more)")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate or verify docs/REPO_MAP.md.")
    parser.add_argument("--check", action="store_true", help="Exit 1 if docs/REPO_MAP.md is out of date.")
    parser.add_argument("--stdout", action="store_true", help="Print the map to stdout instead of writing.")
    args = parser.parse_args(argv)

    content = build_repo_map()
    if args.stdout:
        print(content, end="")
        return 0

    if args.check:
        if not DEFAULT_OUT.is_file():
            print("docs/REPO_MAP.md is missing. Run: python rov.py map")
            return 1
        existing = DEFAULT_OUT.read_text(encoding="utf-8", errors="replace")
        if existing != content:
            print("docs/REPO_MAP.md is out of date. Run: python rov.py map")
            return 1
        print("Repo map check passed: docs/REPO_MAP.md is up to date.")
        return 0

    DEFAULT_OUT.parent.mkdir(parents=True, exist_ok=True)
    DEFAULT_OUT.write_text(content, encoding="utf-8")
    print(f"Wrote {DEFAULT_OUT.relative_to(REPO_ROOT).as_posix()} ({len(content.splitlines())} lines).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
